"""Generate ttrv/cfg.py, every Blackhole Tensix configuration field, from tt-metal's cfg_defines.h.

  python3 -m ttrv.gen_cfg [path/to/blackhole/cfg_defines.h]

cfg_defines.h defines each field as NAME_ADDR32 (32-bit word index), NAME_SHAMT (shift) and NAME_MASK (the mask
in place, already shifted). Its "Registers for THREAD" section is ThreadConfig (one copy per Tensix thread, written with SETC16); every
other section is Config (shared by the threads, written with RMWCIB / WRCFG or by MMIO at TENSIX_CFG). The two are
separate word spaces: ThreadConfig word 12 and Config word 12 are different registers."""

import re, sys
from pathlib import Path

DEFAULT = Path(__file__).resolve().parents[2] / "tt-metal/tt_metal/hw/inc/internal/tt-1xx/blackhole/cfg_defines.h"
OUT = Path(__file__).resolve().parent / "cfg.py"


def parse(text):
  spaces, space = {"THREAD": {}, "CONFIG": {}}, None
  values = {}
  for line in text.splitlines():
    if m := re.match(r"// Registers for (\w+)", line):
      space = "THREAD" if m[1] == "THREAD" else "CONFIG"
    elif m := re.match(r"#define (\w+)_(ADDR32|SHAMT|MASK) (0x[0-9a-fA-F]+|\d+)$", line):
      name, kind, value = m[1], m[2], int(m[3], 0)
      if name.endswith("_CFGREG_BASE"):
        continue
      values.setdefault(name, {})[kind] = value
      if kind == "ADDR32":
        spaces[space][name] = None
  for fields in spaces.values():
    for name in fields:
      v = values[name]
      mask, shift = v["MASK"], v["SHAMT"]  # the mask is in place (already shifted)
      width = mask.bit_count()
      assert mask == ((1 << width) - 1) << shift, f"{name}: mask {mask:#x} does not match shift {shift}"
      fields[name] = (v["ADDR32"], shift, width)
  return spaces


# The 128-bit unpacker TileDescriptor is one field in cfg_defines.h. Its parts are tt-llk's unpack_tile_descriptor_t
# (tt_llk_blackhole/common/inc/cunpack_common.h): (word offset, shift, width).
TILE_DESCRIPTOR = dict(in_data_format=(0, 0, 4), uncompressed=(0, 4, 1), blobs_per_xy_plane=(0, 8, 4), x_dim=(0, 16, 16),
                       y_dim=(1, 0, 16), z_dim=(1, 16, 16), w_dim=(2, 0, 16))


def main(argv=sys.argv[1:]):
  src = Path(argv[0]) if argv else DEFAULT
  spaces = parse(src.read_text())
  for sec in (0, 1):
    word = spaces["CONFIG"][f"THCON_SEC{sec}_REG0_TileDescriptor"][0]
    for part, (off, shift, width) in TILE_DESCRIPTOR.items():
      spaces["CONFIG"][f"THCON_SEC{sec}_REG0_TileDescriptor_{part}"] = (word + off, shift, width)
  lines = [
    '"""GENERATED by ttrv/gen_cfg.py from tt-metal blackhole/cfg_defines.h (and tt-llk\'s TileDescriptor). Do not edit;',
    "rerun the generator.",
    "",
    "Every Blackhole Tensix configuration field, named as in cfg_defines.h. A Field is bits [shift, shift + width) of",
    "32-bit word `word` in its space: ThreadConfig (per thread, SETC16) or Config (shared, RMWCIB / WRCFG / MMIO). The",
    'two are separate word spaces. Call a field with a value to get a write: THCON_SEC0_REG2_Out_data_format(5)."""',
    "",
    "from .field import Field, Space",
    "",
    "T, C = Space.THREAD, Space.CONFIG",
    "",
  ]
  for space, tag in (("THREAD", "T"), ("CONFIG", "C")):
    lines.append(f"# ---- {space}")
    lines += [f"{name} = Field({tag}, {w}, {sh}, {wd}, {name!r})" for name, (w, sh, wd) in spaces[space].items()]
    lines.append("")
  OUT.write_text("\n".join(lines))
  print(f"{OUT}: {len(spaces['THREAD'])} thread fields, {len(spaces['CONFIG'])} config fields")


if __name__ == "__main__":
  main()
