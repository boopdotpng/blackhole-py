#!/usr/bin/env python3
"""Static instruction census of the shipped llama3 kernels. Writes markdown to stdout.

usage: python3 ttptx/census.py kernels ../tt-isa-documentation > ttptx/census.md
"""
import collections, glob, os, re, sys

kernels, isa_docs = sys.argv[1], sys.argv[2]
LINE = re.compile(r'^\s*([0-9a-f]+):\s+([0-9a-f]{8})\s+(\S+)(.*)$')
STORE_TARGETS = ('MopCfg', 'MOP_CFG', 'cfg[', 'noc_regs', 'riscv_local_mem', 'TensixMMIO', 'tensix_regfile',
                 'UNPACK_CONFIG_SYNC', 'depends on runtime')

stream, template, riscv, stores = (collections.Counter() for _ in range(4))
replayed = collections.Counter()
where = collections.defaultdict(set)
per_kernel = []
for path in sorted(glob.glob(f'{kernels}/llama3-*/*/*.S')):
  model, kernel, risc = path.split('/')[-3], path.split('/')[-2], os.path.basename(path)[:-2]
  n_tt = n_rv = 0
  for line in open(path):
    m = LINE.match(line)
    if not m or 'Unreachable by statically known' in line: continue   # data tables decoded as code
    mnemonic, rest = m.group(3), m.group(4)
    if mnemonic.isupper():
      n_tt += 1; stream[mnemonic] += 1; where['tt', mnemonic].add(kernel)
      if 'Record replay' in rest: replayed[mnemonic] += 1
      continue
    n_rv += 1; riscv[mnemonic] += 1; where['rv', mnemonic].add(kernel)
    t = re.search(r'MOP template instruction · (\S+)', rest)
    if t and t.group(1) != 'NOP': template[t.group(1)] += 1; where['mop', t.group(1)].add(kernel)
    if mnemonic in ('sw', 'sh', 'sb'):
      comment = rest.split('#', 1)[1] if '#' in rest else ''
      stores[next((k for k in STORE_TARGETS if k in comment), 'l1 data / other')] += 1
  if model == 'llama3-1b': per_kernel.append((f'{kernel}/{risc}', n_tt, n_rv))

def table(title, counts, kind, note=''):
  print(f'\n## {title}\n')
  if note: print(note + '\n')
  print('| instruction | count | kernels |\n| --- | ---: | --- |')
  for mnemonic, n in counts.most_common():
    print(f"| `{mnemonic}` | {n} | {', '.join(sorted(where[kind, mnemonic]))} |")

print("""# llama3 instruction census

Static counts over every `.S` in `kernels/llama3-{1b,8b-bf16,8b-fp8}`. Data tables that the disassembler decoded
as instructions ("Unreachable by statically known control flow") are excluded. These count instructions in the
binaries, not instructions executed: a loop body counts once. Generated by `ttptx/census.py`:

```sh
python3 ttptx/census.py kernels ../tt-isa-documentation > ttptx/census.md
```

Conclusions are in `ttptx_isa.md` section 12.

## per kernel (1b)

| kernel/risc | tensix | risc-v |
| --- | ---: | ---: |""")
for name, a, b in per_kernel: print(f'| {name} | {a} | {b} |')
table('tensix, pushed in the instruction stream', stream, 'tt')
print('\nRecorded into replay buffers (subset of the above): ' +
      ', '.join(f'`{k}` {v}' for k, v in replayed.most_common()))
table('tensix, inside MOP templates', template, 'mop',
      'Written to `MopCfg` by risc-v stores, so they never appear in the stream itself.')
table('risc-v', riscv, 'rv')
print('\n## risc-v store targets\n\n| target | count |\n| --- | ---: |')
for k, n in stores.most_common(): print(f'| {k} | {n} |')

docs = set()
for arch in ('WormholeB0', 'BlackholeA0'):
  for p in glob.glob(f'{isa_docs}/{arch}/TensixTile/TensixCoprocessor/*.md'):
    name = os.path.basename(p)[:-3]
    if re.fullmatch(r'[A-Z][A-Z0-9]+(_[A-Za-z0-9]+)*', name) and name not in ('README', 'MOP_CFG'): docs.add(name.split('_')[0])
used = {re.sub(r'\d$', '', m) for m in (*stream, *template)} | set(stream) | set(template)
print('\n## documented tensix instructions never used\n')
print(', '.join(f'`{n}`' for n in sorted(docs - used)))
